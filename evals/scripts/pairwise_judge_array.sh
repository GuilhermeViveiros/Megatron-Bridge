#!/usr/bin/env bash
# ==============================================================================
# Pairwise (discriminative) judge sweep, one Slurm array task per matchup.
# Absolute 1-5 rubric scoring floors out on these PA (projector-alignment,
# frozen-LLM) checkpoints — every checkpoint scores ~1/5 on correctness, so
# there's no signal left to compare against. Pairwise comparison ("which of
# these two captions is closer to the image?") stays sensitive even when both
# individual captions are poor. See evals/judge.py's --captions_b pairwise mode.
#
# Reuses captions already generated by the original sweep — no checkpoint
# loading, no generation step. Same host-env (no container) vLLM setup as
# evals/scripts/rejudge_vision_array.sh — see that script's header for why.
#
# Usage:
#   sbatch evals/scripts/pairwise_judge_array.sh
# ==============================================================================

#SBATCH --job-name=euro-vl-pairwise
#SBATCH --account=e-ext-2025e01-100
#SBATCH --partition=booster
#SBATCH --nodes=1
#SBATCH --ntasks-per-node=1
#SBATCH --gpus-per-node=1
#SBATCH --time=00:30:00
#SBATCH --array=0-4
#SBATCH --output=logs/euro_vl_eval/pairwise_array_%A_%a.out
#SBATCH --error=logs/euro_vl_eval/pairwise_array_%A_%a.err

set -uo pipefail
cd "$HOME/Megatron-Bridge"

export HF_HUB_OFFLINE=1
export PYTHONPATH="$PWD:${PYTHONPATH:-}"
export CUDA_HOME=/e/software/default/stages/2026/software/CUDA/13
export FLASHINFER_WORKSPACE_BASE="/e/scratch/e-ext-2025e01-100/viveiros1/flashinfer_cache_pw${SLURM_ARRAY_TASK_ID}"
mkdir -p "$FLASHINFER_WORKSPACE_BASE"

PY=/e/project1/e-ext-2025e01-100/viveiros1/envs/eurovlm/bin/python3
JUDGE_MODEL="Qwen/Qwen3.8-27B-FP8"

# Task index -> (tag_a, tag_b). First 3 = backend comparison at matched
# checkpoint; last 2 = pil training-progress comparison.
TAGS_A=(pil_10 pil_50 pil_100 pil_10 pil_50)
TAGS_B=(vect_10 vect_50 vect_100 pil_50 pil_100)
TAG_A="${TAGS_A[$SLURM_ARRAY_TASK_ID]}"
TAG_B="${TAGS_B[$SLURM_ARRAY_TASK_ID]}"

echo "=== $(date) | job $SLURM_JOB_ID task $SLURM_ARRAY_TASK_ID | node $SLURMD_NODENAME | $TAG_A vs $TAG_B ==="

MANIFEST_DIR="/e/scratch/e-ext-2025e01-100/viveiros1/vjudge_manifests_pw${SLURM_ARRAY_TASK_ID}"
mkdir -p "$MANIFEST_DIR"
for modality in image multi_image video; do
  sed 's#/opt/Megatron-Bridge#'"$HOME"'/Megatron-Bridge#g' \
    "evals/data/${modality}_eval.jsonl" > "$MANIFEST_DIR/${modality}_eval.jsonl"
done

echo "--- starting vision judge (vLLM, host env, no container) ---"
"$PY" -m vllm.entrypoints.openai.api_server \
    --model "$JUDGE_MODEL" --port 8000 --max-model-len 40960 \
    --gpu-memory-utilization 0.85 --max-num-seqs 256 \
    > "logs/euro_vl_eval/vllm_pairwise_array_${SLURM_JOB_ID}_${SLURM_ARRAY_TASK_ID}.log" 2>&1 &
VLLM_PID=$!

cleanup() {
  echo "--- stopping vLLM (pid $VLLM_PID) $(date) ---"
  kill "$VLLM_PID" 2>/dev/null
  sleep 3
  kill -9 "$VLLM_PID" 2>/dev/null
}
trap cleanup EXIT

echo "--- waiting for judge to become healthy ---"
ready=0
for i in $(seq 1 90); do
  if curl -sS -m 3 http://localhost:8000/health >/dev/null 2>&1; then
    echo "judge healthy after $((i * 10))s"
    ready=1
    break
  fi
  if ! kill -0 "$VLLM_PID" 2>/dev/null; then
    echo "vLLM died during startup"
    break
  fi
  sleep 10
done
if [ "$ready" -ne 1 ]; then
  echo "judge never became healthy, aborting"
  exit 1
fi

for modality in image multi_image video; do
  manifest="$MANIFEST_DIR/${modality}_eval.jsonl"
  captions_a="evals/results/${TAG_A}/${modality}_captions.jsonl"
  captions_b="evals/results/${TAG_B}/${modality}_captions.jsonl"
  [ -s "$captions_a" ] && [ -s "$captions_b" ] || { echo "skip $TAG_A/$TAG_B/$modality: missing captions"; continue; }
  echo "--- pairwise judge $TAG_A vs $TAG_B ($modality) $(date) ---"
  "$PY" -m evals.judge \
      --manifest "$manifest" \
      --captions "$captions_a" --captions_b "$captions_b" \
      --model_tag "$TAG_A" --model_tag_b "$TAG_B" \
      --judge_provider local --judge_model "$JUDGE_MODEL" \
      --out_dir evals/results/judged_pairwise
done

echo "=== $(date) | job $SLURM_JOB_ID task $SLURM_ARRAY_TASK_ID done ($TAG_A vs $TAG_B) ==="
