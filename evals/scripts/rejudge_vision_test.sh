#!/usr/bin/env bash
# ==============================================================================
# SMOKE TEST for the vision-capable re-judge pass — 10 image items, 2 checkpoints
# (vect_10, vect_100), NOT the full sweep. Confirms Qwen/Qwen3.8-27B-FP8 actually
# serves real multimodal judge requests on a dedicated GPU node (the container
# can't load this model — its bundled nvcc/CUDA-toolkit headers can't JIT-compile
# the Gated DeltaNet FlashInfer kernel this architecture needs — so this runs the
# host `eurovlm` venv directly, no apptainer), before committing to the full
# 1,776-item re-judge (evals/scripts/rejudge_vision.sh, not yet written).
#
# Reuses captions already generated by the original sweep — no checkpoint
# loading, no generation step, just judge scoring.
#
# Usage:
#   sbatch evals/scripts/rejudge_vision_test.sh
# ==============================================================================

#SBATCH --job-name=euro-vl-vjudge-test
#SBATCH --account=e-ext-2025e01-100
#SBATCH --partition=booster
#SBATCH --nodes=1
#SBATCH --ntasks-per-node=1
#SBATCH --gpus-per-node=1
#SBATCH --time=00:20:00
#SBATCH --output=logs/euro_vl_eval/vjudge_test_%j.out
#SBATCH --error=logs/euro_vl_eval/vjudge_test_%j.err

set -uo pipefail
cd "$HOME/Megatron-Bridge"

# Compute nodes have no outbound network — the judge model is already cached
# locally (pulled during interactive smoke testing), so skip the metadata check
# huggingface_hub/vllm would otherwise make even for cached files.
export HF_HUB_OFFLINE=1
export PYTHONPATH="$PWD:${PYTHONPATH:-}"
export CUDA_HOME=/e/software/default/stages/2026/software/CUDA/13
export FLASHINFER_WORKSPACE_BASE=/e/scratch/e-ext-2025e01-100/viveiros1/flashinfer_cache_test

PY=/e/project1/e-ext-2025e01-100/viveiros1/envs/eurovlm/bin/python3
JUDGE_MODEL="Qwen/Qwen3.8-27B-FP8"

echo "=== $(date) | job $SLURM_JOB_ID | node $SLURMD_NODENAME | vision-judge smoke test ==="

echo "--- starting vision judge (vLLM, host env, no container) ---"
"$PY" -m vllm.entrypoints.openai.api_server \
    --model "$JUDGE_MODEL" --port 8000 --max-model-len 40960 --gpu-memory-utilization 0.85 --max-num-seqs 256 \
    > "logs/euro_vl_eval/vllm_vjudge_test_${SLURM_JOB_ID}.log" 2>&1 &
VLLM_PID=$!

cleanup() {
  echo "--- stopping vLLM (pid $VLLM_PID) $(date) ---"
  kill "$VLLM_PID" 2>/dev/null
  sleep 3
  kill -9 "$VLLM_PID" 2>/dev/null
}
trap cleanup EXIT

echo "--- waiting for judge to become healthy ---"
ready=0
for i in $(seq 1 60); do
  if curl -sS -m 3 http://localhost:8000/health >/dev/null 2>&1; then
    echo "judge healthy after $((i * 10))s"
    ready=1
    break
  fi
  sleep 10
done
if [ "$ready" -ne 1 ]; then
  echo "judge never became healthy, aborting"
  exit 1
fi

for tag in vect_10 vect_100; do
  echo "--- judge $tag (image, 10-item test slice) $(date) ---"
  "$PY" -m evals.judge \
      --manifest evals/data/image_eval_vjudge_test.jsonl \
      --captions "evals/results/${tag}_vjudge_test/image_captions.jsonl" \
      --model_tag "$tag" --judge_provider local --judge_model "$JUDGE_MODEL" \
      --out_dir evals/results/judged_vision_test
done

echo "=== $(date) | job $SLURM_JOB_ID done ==="
find evals/results/judged_vision_test -name "*.jsonl" -exec echo {} \; -exec cat {} \;
